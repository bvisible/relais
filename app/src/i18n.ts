export type MessageKey = keyof Dictionary;

export const language: "fr" | "en" = navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";

const table: Dictionary = language === "fr" ? fr : en;

export function t(key: MessageKey, args: Record<string, string | number> = {}): string {
  return Object.entries(args).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), table[key]);
}

/** Whether `key` names a message: commands answer some errors with a code. */
export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(table, key);
}
